#!/usr/bin/env bash
# SpendWise AI - Codespaces pre-create step.
#
# Runs as the Dev Container "initializeCommand" on the HOST, BEFORE Docker
# Compose creates any containers. This is required because the Compose file
# interpolates ${POSTGRES_PASSWORD} and ${JWT_SECRET} while parsing itself, which
# happens before any container exists -- so the .env file must already be on
# disk at that point.
#
# Properties:
#   - Generates strong random secrets, never echoed.
#   - Never overwrites an existing .devcontainer/.env.
#   - Exits non-zero on failure so the container does not start half-configured.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="${HERE}/.env"

if [ -f "${ENV_FILE}" ]; then
    echo "==> .devcontainer/.env already exists; leaving it untouched"
    exit 0
fi

echo "==> Generating .devcontainer/.env with random development secrets"

if command -v openssl >/dev/null 2>&1; then
    PG_PASSWORD="$(openssl rand -hex 24)"
    JWT_SECRET="$(openssl rand -hex 48)"
elif command -v python3 >/dev/null 2>&1; then
    PG_PASSWORD="$(python3 -c 'import secrets; print(secrets.token_hex(24))')"
    JWT_SECRET="$(python3 -c 'import secrets; print(secrets.token_hex(48))')"
else
    echo "ERROR: neither openssl nor python3 is available to generate secrets." >&2
    exit 1
fi

# Refuse to write an empty secret rather than producing an unusable stack.
if [ -z "${PG_PASSWORD}" ] || [ -z "${JWT_SECRET}" ]; then
    echo "ERROR: secret generation produced an empty value." >&2
    exit 1
fi

umask 077
cat > "${ENV_FILE}" <<EOF
# Generated by .devcontainer/init-env.sh - development only.
# Git-ignored. Do not commit.
# Deleting this file and rebuilding regenerates the values here, but it does NOT
# change PostgreSQL's credentials: the database already stored its superuser
# password in the persistent Codespaces volume on first initialisation. Rotating
# credentials therefore needs a deliberate database-volume reset (which destroys
# the Codespaces database only - never a local one). See the README.
POSTGRES_USER=spendwise
POSTGRES_PASSWORD=${PG_PASSWORD}
POSTGRES_DB=spendwise_db
JWT_SECRET=${JWT_SECRET}
JWT_ALGORITHM=HS256
JWT_EXPIRE_MINUTES=60
APP_ENV=development
LOG_LEVEL=INFO
EOF

echo "==> .devcontainer/.env created (values not shown)"
